import { HashingEmbedder, cosine, type Embedder } from "./embed.js";

/**
 * Bug → fix cases the agent can retrieve (BLUEPRINT §5.9.2): fixes users confirmed on their real
 * robot (and chose to share), plus labelled synthetic cases from the bug-injection generator.
 * Only the diff, the symptoms/diagnosis and the part names are kept: never the whole sketch.
 */
export interface KnowledgeCase {
  id: string;
  symptoms: string;
  diagnosis: string;
  diff: string;
  /** How many users confirmed this fix (synthetic cases: 0). */
  confirmations: number;
  /** "user": confirmed on a real robot; "synthetic": generated by bug injection, verified in sim. */
  source: "user" | "synthetic";
  /** Board, driver and sensor ids of the design, for context. */
  parts: string[];
}

export type NewCase = Omit<KnowledgeCase, "id" | "confirmations" | "source" | "parts"> &
  Partial<Pick<KnowledgeCase, "source" | "parts">>;

export interface FixKnowledge {
  search(query: string, k?: number): Promise<KnowledgeCase[]>;
  /** Adds a case, or counts one more confirmation of the same diff. */
  add(c: NewCase): Promise<KnowledgeCase>;
}

/** Text a case is embedded and searched by. */
export const caseText = (c: Pick<KnowledgeCase, "symptoms" | "diagnosis" | "diff">) =>
  `${c.symptoms}\n${c.diagnosis}\n${c.diff
    .split("\n")
    .filter((l) => /^[+-][^+-]/.test(l))
    .join("\n")}`;

/** Similarity weighted by confirmations (user cases rank above synthetic ones). */
export const rankScore = (similarity: number, c: Pick<KnowledgeCase, "confirmations" | "source">) =>
  similarity * (1 + 0.15 * Math.log2(1 + c.confirmations)) * (c.source === "user" ? 1 : 0.85);

/** In-memory store (tests, and the API when no database is configured). */
export class MemoryKnowledge implements FixKnowledge {
  private readonly cases: { c: KnowledgeCase; v: number[] }[] = [];
  constructor(private readonly embedder: Embedder = new HashingEmbedder()) {}

  search(query: string, k = 3): Promise<KnowledgeCase[]> {
    const q = this.embedder.embed(query);
    const scored = this.cases
      .map(({ c, v }) => ({ c, sim: cosine(q, v) }))
      .filter((x) => x.sim > 0.1)
      .sort((a, b) => rankScore(b.sim, b.c) - rankScore(a.sim, a.c));
    return Promise.resolve(scored.slice(0, k).map((x) => x.c));
  }

  add(c: NewCase): Promise<KnowledgeCase> {
    const existing = this.cases.find((x) => x.c.diff === c.diff);
    if (existing) {
      if ((c.source ?? "user") === "user") existing.c.confirmations++;
      return Promise.resolve(existing.c);
    }
    const source = c.source ?? "user";
    const added: KnowledgeCase = {
      ...c,
      id: `case-${String(this.cases.length + 1)}`,
      confirmations: source === "user" ? 1 : 0,
      source,
      parts: c.parts ?? [],
    };
    this.cases.push({ c: added, v: this.embedder.embed(caseText(added)) });
    return Promise.resolve(added);
  }
}
