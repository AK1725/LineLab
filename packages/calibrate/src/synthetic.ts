import type { Design, TelemetryRecording, TwinParams } from "@linelab/schema";
import {
  NOMINAL,
  SIM_FIELD,
  Simulation,
  TRACE_CHANNELS,
  TrackField,
  type Controller,
  type RobotModel,
  type SimConfig,
} from "@linelab/sim-core";
import type { Track } from "@linelab/schema";

/**
 * A synthetic "real robot" recording: the simulator runs a robot with *hidden* twin parameters
 * (different from the nominal model) and its sensors and PWM are written out every `periodMs`,
 * exactly as LineLabTelemetry would send them. Used to test calibration end to end without
 * hardware; such recordings are always labelled `source: "synthetic"`.
 */
export function syntheticRecording(args: {
  design: Design;
  buildRobot: (design: Design) => RobotModel;
  hidden: TwinParams;
  track: Track;
  makeController: () => Controller;
  durationMs: number;
  periodMs?: number;
  seed: number;
  config?: Partial<SimConfig>;
  name?: string;
}): TelemetryRecording {
  const robot = args.buildRobot({ ...args.design, calibration: args.hidden });
  const periodMs = args.periodMs ?? 10;
  const sim = new Simulation(robot, new TrackField(args.track, SIM_FIELD), args.makeController(), {
    variation: NOMINAL,
    ...args.config,
    seed: args.seed,
    recordEveryMs: periodMs,
    durationMs: args.durationMs,
  });
  const r = sim.run();
  const tr = r.trace;
  const s0 = TRACE_CHANNELS.length;
  const col = (name: (typeof TRACE_CHANNELS)[number]) => TRACE_CHANNELS.indexOf(name);
  const samples: TelemetryRecording["samples"] = [];
  for (let i = 0; i < tr.count; i++) {
    const g = (k: number) => tr.data[i * tr.stride + k] ?? 0;
    samples.push({
      tMs: g(col("tMs")),
      sensors: Array.from({ length: tr.sensorCount }, (_, c) => Math.max(0, Math.round(g(s0 + c)))),
      pwmLeft: Math.round(g(col("pwmLeft")) * 1000) / 1000,
      pwmRight: Math.round(g(col("pwmRight")) * 1000) / 1000,
      batteryV: Math.round(g(col("batteryV")) * 1000) / 1000,
      lineLost: g(col("lineSeen")) === 0,
      vars: [],
    });
  }
  return {
    format: "linelab-telemetry/1",
    name: args.name ?? "synthetic",
    source: "synthetic",
    sensorCount: tr.sensorCount,
    periodMs,
    trackId: args.track.id,
    notes: [
      "SYNTHETIC: generated by the LineLab simulator from a robot with hidden twin parameters, not recorded from hardware.",
    ],
    samples,
  };
}
