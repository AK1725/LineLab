// Generates src/generated/catalog.ts from data/components/*.json so the browser can import the
// catalog without touching the file system. The output is gitignored; build/typecheck/test run this.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Component, formatIssues } from "@linelab/schema";

const pkgDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = join(pkgDir, "data", "components");
const outDir = join(pkgDir, "src", "generated");

const components = readdirSync(dataDir)
  .filter((f) => f.endsWith(".json"))
  .sort()
  .map((file) => {
    const parsed = Component.safeParse(JSON.parse(readFileSync(join(dataDir, file), "utf8")));
    if (!parsed.success) {
      throw new Error(
        `${file} is invalid (run pnpm db:validate):\n  ${formatIssues(parsed.error).join("\n  ")}`,
      );
    }
    const { $schema: _schema, ...rest } = parsed.data;
    return rest;
  });

mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, "catalog.ts"),
  `// GENERATED by scripts/build-catalog.ts from data/components/*.json. Do not edit.\n` +
    `import type { Component } from "@linelab/schema";\n\n` +
    `export const COMPONENTS: readonly Component[] = ${JSON.stringify(components, null, 1)};\n`,
);
console.log(`catalog: ${components.length} components`);
