// Generates src/generated/catalog.ts from data/components/*.json so the browser can import the
// catalog without touching the file system. The output is gitignored; build/typecheck/test run this.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Chassis, Component, Track, formatIssues } from "@linelab/schema";

const pkgDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = join(pkgDir, "data", "components");
const chassisDir = join(pkgDir, "data", "chassis");
const tracksDir = join(pkgDir, "..", "..", "tracks");
const outDir = join(pkgDir, "src", "generated");

const components = readdirSync(dataDir)
  .filter((f) => f.endsWith(".json"))
  .sort()
  .map((file) => {
    const parsed = Component.safeParse(JSON.parse(readFileSync(join(dataDir, file), "utf8")));
    if (!parsed.success) {
      throw new Error(
        `${file} is invalid (run pnpm db:validate):\n  ${formatIssues(parsed.error).join("\n  ")}`,
      );
    }
    const { $schema: _schema, ...rest } = parsed.data;
    return rest;
  });

const chassis = readdirSync(chassisDir)
  .filter((f) => f.endsWith(".json"))
  .sort()
  .map((file) => {
    const parsed = Chassis.safeParse(JSON.parse(readFileSync(join(chassisDir, file), "utf8")));
    if (!parsed.success) {
      throw new Error(
        `${file} is invalid (run pnpm db:validate):\n  ${formatIssues(parsed.error).join("\n  ")}`,
      );
    }
    const { $schema: _schema, ...rest } = parsed.data;
    return rest;
  });

const tracks = readdirSync(tracksDir)
  .filter((f) => f.endsWith(".json"))
  .sort()
  .map((file) => {
    const parsed = Track.safeParse(JSON.parse(readFileSync(join(tracksDir, file), "utf8")));
    if (!parsed.success) throw new Error(`${file} is invalid (run pnpm db:validate)`);
    const { $schema: _schema, ...rest } = parsed.data;
    return rest;
  });

mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, "catalog.ts"),
  `// GENERATED by scripts/build-catalog.ts from data/**/*.json. Do not edit.\n` +
    `import type { Chassis, Component, Track } from "@linelab/schema";\n\n` +
    `export const COMPONENTS: readonly Component[] = ${JSON.stringify(components, null, 1)};\n\n` +
    `export const CHASSIS: readonly Chassis[] = ${JSON.stringify(chassis, null, 1)};\n\n` +
    `export const TRACKS: readonly Track[] = ${JSON.stringify(tracks, null, 1)};\n`,
);
console.log(
  `catalog: ${components.length} components, ${chassis.length} chassis, ${tracks.length} tracks`,
);
