// Bundle examples/firmware/* (sources and their prebuilt artifacts) into the web app, so the
// examples can be run without a compiler service. Output is gitignored.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..", "examples", "firmware");
const META = {
  good_pid: {
    name: "PID line follower (Nano)",
    board: "arduino:avr:nano",
    artifact: "good_pid.nano.artifact.json",
  },
  blink: { name: "Blink (Nano)", board: "arduino:avr:nano", artifact: "blink.nano.artifact.json" },
  esp32_pid: {
    name: "PID line follower (ESP32)",
    board: "esp32:esp32:esp32",
    artifact: "esp32_pid.esp32.artifact.json",
  },
};
// Learn-mode lessons: buggy fixtures (labelled as lessons, not offered as examples).
const LESSONS = {
  lesson_oscillation: {
    name: "Lesson: an oscillating robot (Kp too high)",
    board: "arduino:avr:nano",
    dir: "buggy/p_too_high",
    file: "p_too_high.ino",
    artifact: "p_too_high.nano.artifact.json",
  },
  lesson_blocking_delay: {
    name: "Lesson: a robot that reacts late (blocking delay)",
    board: "arduino:avr:nano",
    dir: "buggy/blocking_delay",
    file: "blocking_delay.ino",
    artifact: "blocking_delay.nano.artifact.json",
  },
};
const examples = [];
for (const [id, l] of Object.entries(LESSONS)) {
  const dir = join(root, l.dir);
  examples.push({
    id,
    name: l.name,
    board: l.board,
    source: readFileSync(join(dir, l.file), "utf8"),
    artifact: JSON.parse(readFileSync(join(dir, l.artifact), "utf8")),
    lesson: true,
  });
}
for (const id of readdirSync(root).sort()) {
  const m = META[id];
  if (!m) continue;
  const source = readFileSync(join(root, id, `${id}.ino`), "utf8");
  const art = join(root, id, m.artifact);
  examples.push({
    id,
    name: m.name,
    board: m.board,
    source,
    artifact: existsSync(art) ? JSON.parse(readFileSync(art, "utf8")) : null,
  });
}
writeFileSync(
  join(here, "..", "src", "firmware", "examples.generated.ts"),
  `// Generated by scripts/gen-examples.mjs from examples/firmware. Do not edit.\nexport const EXAMPLES_JSON: string = ${JSON.stringify(JSON.stringify(examples))};\nexport const REFERENCE_DESIGN_JSON: string = ${JSON.stringify(readFileSync(join(here, "..", "..", "..", "packages", "sim-core", "fixtures", "reference.design.json"), "utf8"))};\n`,
);
console.log(`examples: ${examples.map((e) => e.id).join(", ")}`);
